/**
 * One-shot generator: builds lib/java-map.ts (committed, no runtime dep).
 * Run: node scripts/generate-java-map.mjs
 * On a proxied network: HTTPS_PROXY=http://host:port node scripts/generate-java-map.mjs
 */
import { writeFileSync } from "node:fs";
import { ProxyAgent, setGlobalDispatcher } from "undici";

const proxy = process.env.HTTPS_PROXY || process.env.HTTP_PROXY;
if (proxy) setGlobalDispatcher(new ProxyAgent(proxy));

const SOURCES = [
  "https://raw.githubusercontent.com/ans-4175/peta-indonesia-geojson/master/indonesia-prov.geojson",
];

const JAVA_NAMES = [
  "banten",
  "dki jakarta",
  "jawa barat",
  "jawa tengah",
  "di yogyakarta",
  "daerah istimewa yogyakarta",
  "yogyakarta",
  "jawa timur",
];

/* Pancoran, South Jakarta (approx) — marker anchor */
const MARKER = { lon: 106.8345, lat: -6.2456 };

/* Deterministic hash jitter so SSR and hydration agree */
function hash(i) {
  let h = (i * 2654435761) >>> 0;
  h ^= h >> 13;
  h = (h * 2246822519) >>> 0;
  return (h % 1000) / 1000;
}

function pointInRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const intersects =
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}

function isJava(lon, lat, rings) {
  return rings.some((ring) => pointInRing(lon, lat, ring));
}

async function main() {
  let gj = null;
  let lastErr = null;
  for (const url of SOURCES) {
    try {
      const res = await fetch(url);
      if (res.ok) {
        gj = await res.json();
        break;
      }
      lastErr = new Error(`HTTP ${res.status}`);
    } catch (e) {
      lastErr = e;
    }
  }
  if (!gj) throw lastErr ?? new Error("no geojson");

  const features = (gj.features || []).filter((f) => {
    const p = f.properties || {};
    const name = String(
      p.Propinsi ?? p.PROVINSI ?? p.provinsi ?? p.name ?? p.NAME ?? "",
    ).toLowerCase();
    return JAVA_NAMES.some((n) => name === n);
  });

  /* Collect outer rings only */
  const rings = [];
  for (const f of features) {
    const g = f.geometry || {};
    if (g.type === "Polygon") rings.push(g.coordinates[0]);
    else if (g.type === "MultiPolygon")
      for (const poly of g.coordinates) rings.push(poly[0]);
  }
  if (rings.length === 0) throw new Error("no Java rings found");

  /* Bounding box */
  let minLon = 999, maxLon = -999, minLat = 999, maxLat = -999;
  for (const ring of rings)
    for (const [lon, lat] of ring) {
      if (lon < minLon) minLon = lon;
      if (lon > maxLon) maxLon = lon;
      if (lat < minLat) minLat = lat;
      if (lat > maxLat) maxLat = lat;
    }

  /* Adaptive grid sampling, target ~800–1500 particles */
  for (const step of [0.105, 0.09, 0.08, 0.07, 0.062, 0.055]) {
    const pts = [];
    let idx = 0;
    for (let lat = maxLat; lat >= minLat; lat -= step) {
      for (let lon = minLon; lon <= maxLon; lon += step, idx++) {
        const jx = (hash(idx) - 0.5) * step * 0.6;
        const jy = (hash(idx + 7919) - 0.5) * step * 0.6;
        if (isJava(lon + jx, lat + jy, rings)) pts.push([lon + jx, lat + jy]);
      }
    }
    if (pts.length >= 700 && pts.length <= 1500) {
      emit(pts, { minLon, maxLon, minLat, maxLat });
      console.log(`step ${step}: ${pts.length} particles`);
      return;
    }
  }
  throw new Error("could not hit density target");
}

function emit(pts, bbox) {
  const { minLon, maxLon, minLat, maxLat } = bbox;
  const W = 1000;
  const H = (W * (maxLat - minLat)) / (maxLon - minLon);
  const nx = (lon) => ((lon - minLon) / (maxLon - minLon)) * W;
  const ny = (lat) => ((maxLat - lat) / (maxLat - minLat)) * H;

  const mk = { x: nx(MARKER.lon), y: ny(MARKER.lat) };
  const ptsLiteral = pts
    .map(([lon, lat]) => `{x:${nx(lon).toFixed(1)},y:${ny(lat).toFixed(1)}}`)
    .join(",");

  const out = `// GENERATED by scripts/generate-java-map.mjs — do not edit by hand.
export const JAVA_MAP_WIDTH = ${W};
export const JAVA_MAP_HEIGHT = ${H.toFixed(1)};
export const JAVA_POINTS: { x: number; y: number }[] = [
  ${ptsLiteral},
];
export const JAKARTA_MARKER = { x: ${mk.x.toFixed(1)}, y: ${mk.y.toFixed(1)} };
`;
  writeFileSync(new URL("../lib/java-map.ts", import.meta.url), out);
  console.log(
    `emitted lib/java-map.ts (${pts.length} pts, marker ${mk.x.toFixed(1)},${mk.y.toFixed(1)})`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
